// Подключаем библиотеку express (CommonJS-синтаксис).
// express — это функция-конструктор, из которой создаётся приложение.
const express = require("express")

// Создаём экземпляр приложения Express.
// В app мы будем регистрировать роуты, middleware и потом запускать сервер.
const app = express()

// Порт, на котором сервер будет слушать входящие запросы.
// 3000 — стандартный девелоперский порт.
const PORT = 3000;

// Регистрируем обработчик GET-запроса на путь "/" (корень: http://localhost:3000/).
// req — объект запроса (данные от клиента), res — объект ответа (то, что отправим).
app.get("/" , (req , res)=>{
    // Отправляем клиенту строку "Za Putina".
    // res.send сам ставит Content-Type (text/html; charset=utf-8) и завершает ответ.
    res.send("Za Putina")
})

// Регистрируем второй роут: GET /about.
// Работает так же, но срабатывает только при совпадении пути и метода.
app.get("/about" , (req , res)=>{
    // Отправляем клиенту строку "О нас".
    res.send("О нас")
})

// Запускаем HTTP-сервер на порту PORT.
// Колбэк выполнится один раз — когда сервер успешно поднялся.
app.listen(PORT , ()=>{
    // Логируем факт запуска сервера в консоль.
    // ${PORT} — подстановка значения переменной PORT в строку.
    console.log(`Yes sir ${PORT}`);
    
})